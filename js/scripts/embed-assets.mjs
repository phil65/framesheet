// Embed the shared in-page runtime (../src/framesheet/runtime.js, the single source of
// truth, also shipped in the Python package) and the sheet font into a generated module.
// Run by `build`, `typecheck` and `test`; the output is git-ignored.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const runtimePath = join(root, "..", "src", "framesheet", "runtime.js");
const fontPath = join(root, "assets", "Aileron-Regular.ttf");

const runtime = readFileSync(runtimePath, "utf8");
const video = readFileSync(join(root, "..", "src", "framesheet", "video.js"), "utf8");
const font = readFileSync(fontPath);
// FreeType (Pillow) places text by the hhea ascender rounded *up* to whole pixels; the
// canvas reports it rounded. Embed the exact ratio so both put the baseline in one place.
function ascenderRatio(ttf) {
  const tables = new Map();
  const count = ttf.readUInt16BE(4);
  for (let i = 0; i < count; i++) {
    const rec = 12 + i * 16;
    tables.set(ttf.toString("latin1", rec, rec + 4), ttf.readUInt32BE(rec + 8));
  }
  const unitsPerEm = ttf.readUInt16BE(tables.get("head") + 18);
  const ascender = ttf.readInt16BE(tables.get("hhea") + 4);
  return ascender / unitsPerEm;
}
const ascent = ascenderRatio(font);
const sha = createHash("sha256").update(runtime, "utf8").digest("hex");
const videoSha = createHash("sha256").update(video, "utf8").digest("hex");

const out = `// GENERATED by scripts/embed-assets.mjs. Do not edit.
// Source of truth: src/framesheet/runtime.js (shared with the Python package).

/** The in-page time-control runtime, byte-identical to the Python package's runtime.js. */
export const RUNTIME_JS: string = ${JSON.stringify(runtime)};

/** sha256 of RUNTIME_JS (hex). */
export const RUNTIME_SHA256: string = ${JSON.stringify(sha)};

/** The in-page video player (wrapper page), byte-identical to the Python package's video.js. */
export const VIDEO_JS: string = ${JSON.stringify(video)};

/** sha256 of VIDEO_JS (hex). */
export const VIDEO_SHA256: string = ${JSON.stringify(videoSha)};

/** Aileron Regular (CC0), the same subset Pillow bundles: sheet/heatmap labels. */
export const FONT_BASE64: string = ${JSON.stringify(font.toString("base64"))};

/** hhea ascender / unitsPerEm of the font (text anchor: ceil(size * ratio) above baseline). */
export const FONT_ASCENT_RATIO: number = ${ascent};
`;
mkdirSync(join(root, "src", "generated"), { recursive: true });
writeFileSync(join(root, "src", "generated", "assets.ts"), out);
console.log(`embedded runtime.js (sha256 ${sha.slice(0, 12)}), video.js (${videoSha.slice(0, 12)}) and font (${font.length} bytes)`);
